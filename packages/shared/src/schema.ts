import { z } from 'zod';
import { COLOR_NAMES } from './types.js';

export const colorNameSchema = z.enum(COLOR_NAMES);

export const characterConfigSchema = z.object({
  version: z.literal(1),
  baseCharacter: z.string().min(1),
  parts: z.record(z.string(), z.string()),
  colors: z.array(z.object({ target: z.string().min(1), color: colorNameSchema })),
  animations: z.array(z.string().min(1)),
});

const hexColor = z.string().regex(/^#[0-9a-fA-F]{6}$/, 'expected #rrggbb');

export const projectStyleSchema = z.object({
  characterHeightPx: z.union([z.literal(32), z.literal(48), z.literal(64)]),
  directions: z.union([z.literal(8), z.literal('5+mirror')]),
  palette: z.discriminatedUnion('mode', [
    z.object({ mode: z.literal('auto'), colors: z.number().int().min(2).max(256) }),
    z.object({ mode: z.literal('fixed'), hex: z.array(hexColor).min(2).max(256) }),
  ]),
  outline: z.enum(['none', 'dark', 'selective']),
  cell: z.union([
    z.literal('auto'),
    z.object({ w: z.number().int().positive(), h: z.number().int().positive() }),
  ]),
  fps: z.union([z.number().positive(), z.literal('fromClip')]),
});

// ---------------------------------------------------------------------------
// Catalog (generated by scripts/build-catalog.ts)
// ---------------------------------------------------------------------------

const idSchema = z.string().regex(/^[a-z0-9_]+$/, 'ids are lower snake_case');

export const catalogAssetSchema = z.object({
  id: idSchema,
  name: z.string(),
  license: z.string(),
  source: z.string(),
  commit: z.string(),
  /** Path relative to the repo's `assets/` directory. The web app serves `assets/` at `/`. */
  root: z.string(),
});

export const catalogCharacterSchema = z.object({
  id: idSchema,
  /** Path relative to `asset.root`. */
  file: z.string(),
  label_vi: z.string(),
  description_vi: z.string().optional(),
  tags: z.array(z.string()),
  /** Rest-pose bounding-box height in metres (from inspection). */
  heightM: z.number().positive(),
  /** Rest-pose extents in the iso camera's image plane, facing S (metres). */
  projected: z.object({
    heightM: z.number().positive(),
    aboveM: z.number(),
    belowM: z.number(),
    widthM: z.number().positive(),
    /** Tallest projected height over the 8 directions. */
    maxHeightM: z.number().positive(),
  }),
  /** Non-skinned mesh nodes bundled inside the GLB that must be hidden unless selected as a part. */
  builtinNodes: z.array(z.string()),
});

export const catalogSlotSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
  /** Bone name the part is parented to (for file parts) or that hosts the builtin mesh. */
  bone: z.string(),
});

export const catalogPartSourceSchema = z.discriminatedUnion('type', [
  /** A separate glTF file attached to the slot bone. */
  z.object({ type: z.literal('file'), file: z.string() }),
  /** A mesh node already inside the character GLB, toggled visible. */
  z.object({ type: z.literal('builtin'), node: z.string() }),
]);

const vec3Schema = z.tuple([z.number(), z.number(), z.number()]);
const quatSchema = z.tuple([z.number(), z.number(), z.number(), z.number()]);

/** Local transform of a file part relative to its slot bone (copied from the GLB's built-in equivalents). */
export const catalogAttachSchema = z.object({ translation: vec3Schema, rotation: quatSchema });

export const catalogPartSchema = z.object({
  id: idSchema,
  slots: z.array(idSchema).min(1),
  label_vi: z.string(),
  tags: z.array(z.string()),
  /** Character ids this part fits, or ["*"] for all. */
  characters: z.array(z.string()).min(1),
  source: catalogPartSourceSchema,
  /** slotId -> local transform. Only for file parts; missing means identity. */
  attach: z.record(idSchema, catalogAttachSchema).optional(),
});

export const catalogColorTargetSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
  kind: z.enum(['mesh', 'slot']),
  /** kind=mesh: character mesh node names end with one of these suffixes (e.g. "_Body"). */
  meshSuffixes: z.array(z.string()).optional(),
  /** kind=slot: recolors whatever part is in this slot. */
  slot: idSchema.optional(),
});

export const catalogColorSchema = z.object({
  id: colorNameSchema,
  label_vi: z.string(),
  /** Representative sRGB hex. "original" keeps the texture. */
  hex: hexColor,
});

export const catalogAnimationSchema = z.object({
  id: idSchema,
  clip: z.string(),
  label_vi: z.string(),
  loop: z.boolean(),
  defaultFrames: z.number().int().min(1).max(64),
  durationS: z.number().positive(),
  /** True when the clip moves the character horizontally (measured by inspect-assets). */
  rootMotion: z.boolean(),
  tags: z.array(z.string()),
});

export const catalogSchema = z.object({
  version: z.literal(1),
  asset: catalogAssetSchema,
  referenceCharacter: idSchema,
  characters: z.array(catalogCharacterSchema).min(1),
  slots: z.array(catalogSlotSchema).min(1),
  parts: z.array(catalogPartSchema),
  colorTargets: z.array(catalogColorTargetSchema).min(1),
  colors: z.array(catalogColorSchema).length(COLOR_NAMES.length),
  animations: z.array(catalogAnimationSchema).min(1),
});

export type Catalog = z.infer<typeof catalogSchema>;
export type CatalogCharacter = z.infer<typeof catalogCharacterSchema>;
export type CatalogSlot = z.infer<typeof catalogSlotSchema>;
export type CatalogPart = z.infer<typeof catalogPartSchema>;
export type CatalogPartSource = z.infer<typeof catalogPartSourceSchema>;
export type CatalogAttach = z.infer<typeof catalogAttachSchema>;
export type CatalogColorTarget = z.infer<typeof catalogColorTargetSchema>;
export type CatalogColor = z.infer<typeof catalogColorSchema>;
export type CatalogAnimation = z.infer<typeof catalogAnimationSchema>;

/**
 * Cross-reference checks that zod alone cannot express.
 * Returns a list of human-readable problems; empty means valid.
 */
export function checkCatalogReferences(catalog: Catalog): string[] {
  const problems: string[] = [];
  const charIds = new Set(catalog.characters.map((c) => c.id));
  const slotIds = new Set(catalog.slots.map((s) => s.id));
  const animIds = new Set<string>();
  const partIds = new Set<string>();
  const colorTargetIds = new Set<string>();

  if (!charIds.has(catalog.referenceCharacter)) {
    problems.push(`referenceCharacter "${catalog.referenceCharacter}" is not a character`);
  }
  for (const part of catalog.parts) {
    if (partIds.has(part.id)) problems.push(`duplicate part id "${part.id}"`);
    partIds.add(part.id);
    for (const slot of part.slots) {
      if (!slotIds.has(slot)) problems.push(`part "${part.id}" references unknown slot "${slot}"`);
    }
    for (const ch of part.characters) {
      if (ch !== '*' && !charIds.has(ch)) {
        problems.push(`part "${part.id}" references unknown character "${ch}"`);
      }
    }
    if (part.attach) {
      if (part.source.type !== 'file')
        problems.push(`part "${part.id}" has attach but is not a file part`);
      for (const slot of Object.keys(part.attach)) {
        if (!part.slots.includes(slot))
          problems.push(`part "${part.id}" attach slot "${slot}" is not in its slots`);
      }
    }
    if (part.source.type === 'builtin') {
      const owners = part.characters.includes('*')
        ? catalog.characters
        : catalog.characters.filter((c) => part.characters.includes(c.id));
      for (const owner of owners) {
        if (!owner.builtinNodes.includes(part.source.node)) {
          problems.push(
            `builtin part "${part.id}" node "${part.source.node}" not found in character "${owner.id}"`,
          );
        }
      }
    }
  }
  for (const t of catalog.colorTargets) {
    if (colorTargetIds.has(t.id)) problems.push(`duplicate colorTarget id "${t.id}"`);
    colorTargetIds.add(t.id);
    if (t.kind === 'slot' && (!t.slot || !slotIds.has(t.slot))) {
      problems.push(`colorTarget "${t.id}" references unknown slot "${t.slot ?? ''}"`);
    }
    if (t.kind === 'mesh' && (!t.meshSuffixes || t.meshSuffixes.length === 0)) {
      problems.push(`colorTarget "${t.id}" has no meshSuffixes`);
    }
  }
  for (const a of catalog.animations) {
    if (animIds.has(a.id)) problems.push(`duplicate animation id "${a.id}"`);
    animIds.add(a.id);
  }
  const colorIds = new Set(catalog.colors.map((c) => c.id));
  for (const name of COLOR_NAMES) {
    if (!colorIds.has(name)) problems.push(`colors is missing "${name}"`);
  }
  return problems;
}
