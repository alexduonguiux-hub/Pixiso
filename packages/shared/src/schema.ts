import { z } from 'zod';
import { COLOR_NAMES, DIRECTIONS_8 } from './types.js';

export const colorNameSchema = z.enum(COLOR_NAMES);

const hexColor = z.string().regex(/^#[0-9a-fA-F]{6}$/, 'expected #rrggbb');
/** A named colour of the catalog, or an exact `#rrggbb` (D-096: presets keep the cast's measured colours). */
export const colorValueSchema = colorNameSchema.or(hexColor as z.ZodType<`#${string}`>);

export const characterConfigSchema = z.object({
  version: z.literal(1),
  baseCharacter: z.string().min(1),
  parts: z.record(z.string(), z.string()),
  colors: z.array(z.object({ target: z.string().min(1), color: colorValueSchema })),
  animations: z.array(z.string().min(1)),
});

export const projectStyleSchema = z.object({
  characterHeightPx: z.union([z.literal(32), z.literal(64)]),
  directions: z.union([z.literal(8), z.literal('5+mirror')]),
  palette: z.discriminatedUnion('mode', [
    z.object({ mode: z.literal('auto'), colors: z.number().int().min(2).max(256) }),
    z.object({ mode: z.literal('fixed'), hex: z.array(hexColor).min(2).max(256) }),
  ]),
  outline: z.enum(['ink', 'soft', 'none']),
  cell: z.union([
    z.literal('auto'),
    z.object({ w: z.number().int().positive(), h: z.number().int().positive() }),
  ]),
  fps: z.union([z.number().positive(), z.literal('fromClip')]),
});

// ---------------------------------------------------------------------------
// Catalog (generated by scripts/build-catalog.ts from the sprite-kit registry
// and scripts/catalog-labels.yaml)
// ---------------------------------------------------------------------------

const idSchema = z.string().regex(/^[a-z0-9_]+$/, 'ids are lower snake_case');

export const directionSchema = z.enum(DIRECTIONS_8);

/** Provenance of the drawn templates. Everything is authored in this repository. */
export const catalogSourceSchema = z.object({
  id: idSchema,
  name: z.string(),
  license: z.string(),
  note: z.string().optional(),
});

/** A base body: a set of pixel templates per view on a fixed canvas. */
export const catalogCharacterSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
  description_vi: z.string().optional(),
  tags: z.array(z.string()),
  /** Native canvas of one frame, pixels. */
  canvas: z.object({ w: z.number().int().positive(), h: z.number().int().positive() }),
  /** Foot anchor inside the canvas (pixel coordinates, top-left origin). */
  pivot: z.object({ x: z.number().int().min(0), y: z.number().int().min(0) }),
});

export const catalogSlotSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
});

export const catalogPartSchema = z.object({
  id: idSchema,
  slots: z.array(idSchema).min(1),
  label_vi: z.string(),
  tags: z.array(z.string()),
  /** Character ids this part fits, or ["*"] for all. */
  characters: z.array(z.string()).min(1),
});

/** A recolourable region: every colour target maps to one sprite-kit material. */
export const catalogColorTargetSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
  material: idSchema,
});

export const catalogColorSchema = z.object({
  id: colorNameSchema,
  label_vi: z.string(),
  /** Base sRGB hex of the ramp. "original" keeps the material's default colour. */
  hex: hexColor,
});

export const catalogAnimationSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
  loop: z.boolean(),
  /** Frames drawn for this clip (fixed, not sampled). */
  frames: z.number().int().min(1).max(64),
  /** Milliseconds per frame at the clip's own speed. */
  frameMs: z.number().int().min(10),
  tags: z.array(z.string()),
  /** Character ids that have frames for this clip, or ["*"] for all (absent: all). */
  characters: z.array(z.string()).min(1).optional(),
});

/** A ready-made character: a full config on one body (the Vùng Xanh cast on the hero body, D-096). */
export const catalogPresetSchema = z.object({
  id: idSchema,
  label_vi: z.string(),
  description_vi: z.string().optional(),
  tags: z.array(z.string()),
  config: characterConfigSchema,
});

export const catalogSchema = z.object({
  version: z.literal(2),
  source: catalogSourceSchema,
  referenceCharacter: idSchema,
  characters: z.array(catalogCharacterSchema).min(1),
  slots: z.array(catalogSlotSchema).min(1),
  parts: z.array(catalogPartSchema),
  colorTargets: z.array(catalogColorTargetSchema).min(1),
  colors: z.array(catalogColorSchema).length(COLOR_NAMES.length),
  animations: z.array(catalogAnimationSchema).min(1),
  /** Directions that can be rendered today (the rest arrive with more drawn views). */
  directions: z.array(directionSchema).min(1),
  presets: z.array(catalogPresetSchema).default([]),
});

export type Catalog = z.infer<typeof catalogSchema>;
export type CatalogSource = z.infer<typeof catalogSourceSchema>;
export type CatalogCharacter = z.infer<typeof catalogCharacterSchema>;
export type CatalogSlot = z.infer<typeof catalogSlotSchema>;
export type CatalogPart = z.infer<typeof catalogPartSchema>;
export type CatalogColorTarget = z.infer<typeof catalogColorTargetSchema>;
export type CatalogColor = z.infer<typeof catalogColorSchema>;
export type CatalogAnimation = z.infer<typeof catalogAnimationSchema>;
export type CatalogPreset = z.infer<typeof catalogPresetSchema>;

/**
 * Cross-reference checks that zod alone cannot express.
 * Returns a list of human-readable problems; empty means valid.
 */
export function checkCatalogReferences(catalog: Catalog): string[] {
  const problems: string[] = [];
  const charIds = new Set<string>();
  for (const c of catalog.characters) {
    if (charIds.has(c.id)) problems.push(`duplicate character id "${c.id}"`);
    charIds.add(c.id);
    if (c.pivot.x >= c.canvas.w || c.pivot.y >= c.canvas.h) {
      problems.push(`character "${c.id}" pivot lies outside its canvas`);
    }
  }
  if (!charIds.has(catalog.referenceCharacter)) {
    problems.push(`referenceCharacter "${catalog.referenceCharacter}" is not a character`);
  }
  const slotIds = new Set<string>();
  for (const s of catalog.slots) {
    if (slotIds.has(s.id)) problems.push(`duplicate slot id "${s.id}"`);
    slotIds.add(s.id);
  }
  const partIds = new Set<string>();
  for (const part of catalog.parts) {
    if (partIds.has(part.id)) problems.push(`duplicate part id "${part.id}"`);
    partIds.add(part.id);
    for (const slot of part.slots) {
      if (!slotIds.has(slot)) problems.push(`part "${part.id}" references unknown slot "${slot}"`);
    }
    for (const ch of part.characters) {
      if (ch !== '*' && !charIds.has(ch)) {
        problems.push(`part "${part.id}" references unknown character "${ch}"`);
      }
    }
  }
  const targetIds = new Set<string>();
  for (const t of catalog.colorTargets) {
    if (targetIds.has(t.id)) problems.push(`duplicate colorTarget id "${t.id}"`);
    targetIds.add(t.id);
  }
  const animIds = new Set<string>();
  for (const a of catalog.animations) {
    if (animIds.has(a.id)) problems.push(`duplicate animation id "${a.id}"`);
    animIds.add(a.id);
  }
  const colorIds = new Set(catalog.colors.map((c) => c.id));
  for (const name of COLOR_NAMES) {
    if (!colorIds.has(name)) problems.push(`colors is missing "${name}"`);
  }
  const dirs = new Set<string>();
  for (const d of catalog.directions) {
    if (dirs.has(d)) problems.push(`duplicate direction "${d}"`);
    dirs.add(d);
  }
  for (const a of catalog.animations)
    for (const ch of a.characters ?? [])
      if (ch !== '*' && !charIds.has(ch))
        problems.push(`animation "${a.id}" references unknown character "${ch}"`);
  const presetIds = new Set<string>();
  for (const p of catalog.presets) {
    if (presetIds.has(p.id)) problems.push(`duplicate preset id "${p.id}"`);
    presetIds.add(p.id);
    if (!charIds.has(p.config.baseCharacter))
      problems.push(`preset "${p.id}" uses unknown character "${p.config.baseCharacter}"`);
    for (const [slot, part] of Object.entries(p.config.parts)) {
      if (!slotIds.has(slot)) problems.push(`preset "${p.id}" uses unknown slot "${slot}"`);
      if (part !== 'none' && !partIds.has(part))
        problems.push(`preset "${p.id}" uses unknown part "${part}"`);
    }
    for (const id of p.config.animations)
      if (!animIds.has(id)) problems.push(`preset "${p.id}" uses unknown animation "${id}"`);
  }
  return problems;
}
