/** The base head (chin line only on its last row) centred on the body. */
export function buildHeavyFigure(): Sprite {
  const out = blank(HEAVY_FIGURE_W, HEAVY_FIGURE_H);
  out.cells.set(HEAVY_BODY.cells);
  const head = cut(
    HERO_S_FIGURE,
    [1, 0, 15, 14],
    [
      [1, 14, 5, 14],
      [11, 14, 15, 14],
    ],
  );
  const x0 = (HEAVY_FIGURE_W - 17) / 2 + 1; // base column 1 lands here
  for (let k = 0; k < head.h; k++)
    for (let j = 0; j < head.w; j++) {
      const v = head.cells[k * head.w + j]!;
      if (v >= 0) out.cells[k * out.w + x0 + j] = v;
    }
  return out;
}

export const HERO_HEAVY_S: Sprite = buildHeavyFigure();
